def _render_subprocessors_catalog(modules) -> str:
    """The register a clinic needs for its processing agreement.

    Generated from ``manifest.egress`` so it cannot drift from what the
    code actually does — the failure mode of a hand-kept register is that
    it is correct on the day it is written and wrong the next time
    somebody adds a module.
    """
    lines: list[str] = [
        GENERATED_HEADER,
        "# Subprocessors catalog\n",
        "Every destination outside this deployment that an installed module "
        "sends data to, declared in `manifest.egress` (ADR 0027). This is the "
        "register a clinic needs for its data-processing agreement.\n",
        "A destination is permitted only if its `target` appears in "
        "`TENANT_EGRESS_ALLOWED`. Today an undeclared destination is reported "
        "at boot, not blocked — see ADR 0027 for why.\n",
        "Maintained by `backend/scripts/generate_catalogs.py`. CI fails if a "
        "manifest changes without re-generation.\n",
        "| Module | Target | Subprocessor | Residency | Data | Required | Purpose |",
        "|--------|--------|--------------|-----------|------|----------|---------|",
    ]

    rows = []
    for module in modules:
        for entry in module.get_manifest().egress:
            data = ", ".join(sorted(c.value for c in entry.data_classes)) or "none"
            rows.append(
                f"| `{module.name}` | `{entry.target}` | {entry.subprocessor} | "
                f"{entry.residency} | {data} | "
                f"{'yes' if entry.required else 'optional'} | {entry.purpose} |"
            )
    if rows:
        lines.extend(sorted(rows))
    else:
        lines.append("| — | — | No module declares egress. | — | — | — | — |")

    lines.append("")
    lines.append("## Modules that send nothing off-premises\n")
    silent = sorted(m.name for m in modules if not m.get_manifest().egress)
    lines.append(", ".join(f"`{n}`" for n in silent) if silent else "None.")
    lines.append("")
    return "\n".join(lines)


TIER_LABEL = {"base": "base", "core": "core", "optional": "optional"}


def _load_apps() -> list[dict]:
    """``apps.json`` as written — the catalog of Apps (ADR 0036, 0043)."""
    import json

    return json.loads(APPS_FILE.read_text(encoding="utf-8"))["apps"]


def _render_apps_catalog(modules) -> str:
    """Every App, the modules it groups and what they need from outside.

    Built from ``apps.json`` and the manifests alone, so it says what the
    code declares rather than what a hand-written page remembers.
    """
    manifests = {m.name: m.get_manifest() for m in modules}
    apps = _load_apps()
    owner = {module: app["name"] for app in apps for module in app["modules"]}

    def outside(app: dict, attribute: str) -> list[str]:
        """Apps other than ``app`` that its modules ``depends``/``integrates``."""
        found: list[str] = []
        for module in app["modules"]:
            for other in getattr(manifests[module], attribute):
                target = owner.get(other)
                if target and target != app["name"] and target not in found:
                    found.append(target)
        return found

    lines: list[str] = [
        GENERATED_HEADER,
        "# Apps catalog\n",
        "Every App of the deployment, from `backend/apps.json`: its tier, the "
        "modules it groups, the Apps those modules require and the ones they "
        "only integrate with. An App is what a clinic chooses; a module is what "
        "the code is made of ([ADR 0036](adr/0036-an-app-is-a-declared-group-of-modules.md), "
        "[ADR 0043](adr/0043-the-workspace-is-the-base-app.md)).\n",
        "Maintained by `backend/scripts/generate_catalogs.py`. CI fails if "
        "`apps.json` or a manifest changes without re-generation. What each "
        "App is for lives in `docs/apps/<app>/README.md`.\n",
        "## Summary\n",
        "| App | Version | Tier | Status | Modules | Requires Apps | Integrates with Apps | APIs |",
        "|-----|---------|------|--------|---------|---------------|----------------------|------|",
    ]
    for app in apps:
        apis = ", ".join(f"{api['name']} ({api['status']})" for api in app.get("apis", [])) or "—"
        requires = outside(app, "depends")
        lines.append(
            f"| [`{app['name']}`](apps/{app['name']}/README.md) | {app['version']} "
            f"| {TIER_LABEL[app.get('tier', 'optional')]} | {app['status']} "
            f"| {', '.join(app['modules']) or '— (core + shell)'} "
            f"| {', '.join(requires) or '—'} "
            f"| {', '.join(a for a in outside(app, 'integrates') if a not in requires) or '—'} "
            f"| {apis} |"
        )

    lines.append("\n## Modules by App\n")
    for app in apps:
        lines.append(f"### `{app['name']}`\n")
        if not app["modules"]:
            lines.append(
                "No modules: the core (`backend/app/core/`) and the host frontend "
                "(`frontend/app/`).\n"
            )
            continue
        lines.append("| Module | Version | Install | Depends | Integrates |")
        lines.append("|--------|---------|---------|---------|------------|")
        for module in app["modules"]:
            manifest = manifests[module]
            install = (
                "auto" if manifest.auto_install else ("manual" if manifest.installable else "no")
            )
            lines.append(
                f"| `{module}` | {manifest.version} | {install} "
                f"| {', '.join(manifest.depends) or '—'} "
                f"| {', '.join(manifest.integrates) or '—'} |"
            )
        lines.append("")

    unassigned = sorted(set(manifests) - set(owner))
    if unassigned:
        lines.append("## Modules without an App\n")
        lines.extend(f"- `{name}`" for name in unassigned)
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def _apps_missing_docs() -> list[str]:
    """Apps without their ``docs/apps/<app>/README.md`` and ``CHANGELOG.md``."""
    missing: list[str] = []
    for app in _load_apps():
        for name in ("README.md", "CHANGELOG.md"):
            path = APPS_DOCS / app["name"] / name
            if not path.exists():
                missing.append(path.relative_to(REPO_ROOT).as_posix())
    return missing


def _render_modules_catalog(modules, publishers) -> str:
    lines: list[str] = [
        GENERATED_HEADER,
        "# Modules catalog\n",
        "Single source of truth for every module loaded into the running "
        "Diente Azul instance. Generated from module manifests, "
        "`get_permissions()`, `get_event_handlers()`, and grep of "
        "`event_bus.publish` callsites.\n",
        "Maintained by `backend/scripts/generate_catalogs.py`. CI fails "
        "if a manifest changes without re-generation.\n",
        "## Summary\n",
        "| Module | Version | Category | Depends | Integrates | Install | Removable | Permissions | Emits | Consumes | FE layer |",
        "|--------|---------|----------|---------|------------|---------|-----------|-------------|-------|----------|----------|",
    ]

    by_name = {m.name: m for m in modules}
    for name in sorted(by_name):
        module = by_name[name]
        manifest = module.get_manifest()
        depends = ", ".join(manifest.depends) or "—"
        integrates = ", ".join(manifest.integrates) or "—"
        install = "auto" if manifest.auto_install else ("manual" if manifest.installable else "no")
        removable = "yes" if manifest.removable else "no"
        perms = len(module.get_permissions())
        emitted = sum(
            1
            for event, sites in publishers.items()
            for module_name, _, _ in sites
            if module_name == name
        )
        consumed = len(module.get_event_handlers())
        fe = "yes" if (manifest.frontend or {}).get("layer_path") else "no"
        lines.append(
            f"| `{name}` | {manifest.version} | {manifest.category.value} | "
            f"{depends} | {integrates} | {install} | {removable} | {perms} | {emitted} | "
            f"{consumed} | {fe} |"
        )

    lines.append("")
    lines.append("## Modules\n")

    for name in sorted(by_name):
        module = by_name[name]
        manifest = module.get_manifest()
        permissions = sorted(module.get_permissions())
        consumed = sorted(module.get_event_handlers().keys())
        emitted = sorted(
            {
                event
                for event, sites in publishers.items()
                for module_name, _, _ in sites
                if module_name == name
            }
        )

        lines.append(f"### `{name}` — v{manifest.version}\n")
        if manifest.summary:
            lines.append(manifest.summary + "\n")
        lines.append(f"- **Author:** {manifest.author or '—'}")
        lines.append(f"- **License:** {manifest.license or '—'}")
        lines.append(f"- **Category:** {manifest.category.value}")
        lines.append(
            "- **Install policy:** "
            f"installable={manifest.installable} · "
            f"auto_install={manifest.auto_install} · "
            f"removable={manifest.removable}"
        )
        lines.append(
            "- **Depends:** "
            + (", ".join(f"`{d}`" for d in manifest.depends) if manifest.depends else "—")
        )
        lines.append(
            "- **Integrates:** "
            + (", ".join(f"`{d}`" for d in manifest.integrates) if manifest.integrates else "—")
        )
        lines.append(
            "- **Frontend layer:** "
            + (
                f"`{(manifest.frontend or {}).get('layer_path')}`"
                if (manifest.frontend or {}).get("layer_path")
                else "—"
            )
        )
        if permissions:
            lines.append("- **Permissions:**")
            for perm in permissions:
                lines.append(f"  - `{name}.{perm}`")
        else:
            lines.append("- **Permissions:** —")
        if emitted:
            lines.append("- **Events emitted:**")
            for event in emitted:
                lines.append(f"  - `{event}`")
        else:
            lines.append("- **Events emitted:** —")
        if consumed:
            lines.append("- **Events consumed:**")
            for event in consumed:
                lines.append(f"  - `{event}`")
        else:
            lines.append("- **Events consumed:** —")

        per_module_doc = MODULES_ROOT / name / "CLAUDE.md"
        if per_module_doc.exists():
            rel = per_module_doc.relative_to(REPO_ROOT).as_posix()
            lines.append(f"- **Module CLAUDE.md:** [`{rel}`](../{rel})")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _render_events_catalog(modules, publishers) -> str:
    lines: list[str] = [
        GENERATED_HEADER,
        "# Events catalog\n",
        "Every event declared in `app.core.events.types.EventType`, with "
        "its publishers (grepped from `event_bus.publish` callsites) and "
        "subscribers (modules that return the event from "
        "`get_event_handlers()`).\n",
        "Maintained by `backend/scripts/generate_catalogs.py`.\n",
        "## Summary\n",
        "| Event | Constant | Publishers | Subscribers |",
        "|-------|----------|------------|-------------|",
    ]

    subscribers_by_event: dict[str, list[str]] = defaultdict(list)
    for module in modules:
        for event_name in module.get_event_handlers():
            subscribers_by_event[event_name].append(module.name)
    for entries in subscribers_by_event.values():
        entries.sort()

    for const, value in _all_event_types():
        pubs = publishers.get(value, [])
        subs = subscribers_by_event.get(value, [])
        pub_modules = sorted({m for m, _, _ in pubs})
        lines.append(
            f"| `{value}` | `EventType.{const}` | "
            f"{', '.join(f'`{m}`' for m in pub_modules) or '—'} | "
            f"{', '.join(f'`{s}`' for s in subs) or '—'} |"
        )

    # Surface "feral" events — strings published in code but not in the enum.
    feral = sorted(set(publishers) - {value for _, value in _all_event_types()})
    if feral:
        lines.append("")
        lines.append("## Events published but missing from `EventType` enum\n")
        lines.append(
            "These literals appear in `event_bus.publish(...)` but do not "
            "match any `EventType` constant. Add them to "
            "`backend/app/core/events/types.py` to keep the enum "
            "authoritative.\n"
        )
        for event in feral:
            sites = publishers[event]
            lines.append(f"- `{event}` — {len(sites)} site(s):")
            for _, relpath, _ in sites:
                lines.append(f"  - `{relpath}`")

    lines.append("")
    lines.append("## Detail\n")

    for const, value in _all_event_types():
        pubs = publishers.get(value, [])
        subs = subscribers_by_event.get(value, [])
        lines.append(f"### `{value}`\n")
        lines.append(f"- **Constant:** `EventType.{const}`")
        if pubs:
            lines.append("- **Publishers:**")
            # File, not file:line. The line number is still scanned — the
            # feral-event CI annotation points at the exact callsite with
            # it — but rendering it here made the catalog go stale on any
            # edit that shifted lines above a publish call, with nothing
            # about the events having changed.
            for module_name, relpath, _ in pubs:
                lines.append(f"  - `{module_name}` — `{relpath}`")
        else:
            lines.append("- **Publishers:** _none in tree — declared but unused_")
        if subs:
            lines.append("- **Subscribers:**")
            for module_name in subs:
                lines.append(f"  - `{module_name}`")
        else:
            lines.append("- **Subscribers:** —")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


