def _render_errors_catalog(modules) -> str:
    """Every case a module can refuse for, in one place.

    The codes themselves stay with their module — ``errors.json`` beside
    the code that raises them, which is what makes the module the owner
    of its own contract (ADR 0001). What did not exist was anywhere to
    read all of them: a support call quoting ``budget.public_link.locked``
    sent whoever answered it grepping through twenty-five files.

    So this aggregates rather than replaces. Nothing here is authored;
    editing it is editing the wrong file.
    """
    import json

    lines: list[str] = [
        GENERATED_HEADER,
        "# Errors catalog\n",
        "Every failure an installed module can name, from its "
        "`errors.json`. A code is `<module>.<resource>.<case>` and is read "
        "as it is — see `backend/app/core/errors.py` for why the API "
        "answers with a code, a category and a reference.\n",
        "The **category** is what a screen reacts to; the **status** is what "
        "the HTTP answer carries; the **message** is what the caller is "
        "shown when the raiser is given no more specific detail.\n",
        "`tests/test_error_catalog_contract.py` keeps these in step with the "
        "code that raises them. This file is generated by "
        "`backend/scripts/generate_catalogs.py`; re-run it after changing an "
        "`errors.json`, and `--check` reports drift.\n",
    ]

    catalogs: dict[str, list[dict]] = {}
    uncatalogued: list[str] = []
    for module in modules:
        path = MODULES_ROOT / module.name / "errors.json"
        if not path.exists():
            uncatalogued.append(module.name)
            continue
        catalogs[module.name] = json.loads(path.read_text(encoding="utf-8"))["errors"]

    total = sum(len(v) for v in catalogs.values())
    lines.append(f"{total} codes across {len(catalogs)} modules.\n")

    lines.append("| Module | Codes |")
    lines.append("|--------|-------|")
    for name in sorted(catalogs):
        # GitHub keeps underscores in heading anchors, so the module name
        # is the anchor. Replacing them with hyphens is how this table
        # came to link at nothing.
        lines.append(f"| [`{name}`](#{name}) | {len(catalogs[name])} |")
    lines.append("")

    if uncatalogued:
        lines.append("## Modules with no catalog yet\n")
        lines.append(
            "These raise bare `HTTPException`, so their failures reach the "
            "caller with a category and a reference but no code: "
            + ", ".join(f"`{n}`" for n in sorted(uncatalogued))
            + ".\n"
        )

    for name in sorted(catalogs):
        lines.append(f"## {name}\n")
        lines.append("| Code | Category | Status | Message | Description |")
        lines.append("|------|----------|--------|---------|-------------|")
        for entry in sorted(catalogs[name], key=lambda e: e["code"]):
            lines.append(
                f"| `{entry['code']}` | {entry['category']} | "
                f"{entry['status_code']} | {entry['message']} | "
                f"{entry['description']} |"
            )
        lines.append("")

    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify the committed catalogs match the freshly generated content; exit 1 on drift.",
    )
    args = parser.parse_args(argv)

    modules = discover_modules()
    publishers = _scan_publishers()

    new_modules_text = _render_modules_catalog(modules, publishers)
    new_events_text = _render_events_catalog(modules, publishers)
    new_subprocessors_text = _render_subprocessors_catalog(modules)
    new_apps_text = _render_apps_catalog(modules)
    new_errors_text = _render_errors_catalog(modules)

    if args.check:
        drift = False
        for path, expected in (
            (MODULES_CATALOG, new_modules_text),
            (EVENTS_CATALOG, new_events_text),
            (SUBPROCESSORS_CATALOG, new_subprocessors_text),
            (APPS_CATALOG, new_apps_text),
            (ERRORS_CATALOG, new_errors_text),
        ):
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if actual != expected:
                drift = True
                rel = path.relative_to(REPO_ROOT).as_posix()
                print(
                    f"::error::{rel} is stale. "
                    f"Run `python backend/scripts/generate_catalogs.py` and commit.",
                    file=sys.stderr,
                )

        # Every App is documented where a person will look for it.
        for missing in _apps_missing_docs():
            drift = True
            print(
                f"::error::{missing} is missing — every App in apps.json has one.", file=sys.stderr
            )

        # Fail if any ``event_bus.publish`` callsite uses a string literal
        # that is not in ``EventType``. The catalog already lists them;
        # this turns the listing into an actionable CI gate so the enum
        # stays the source of truth as third-party modules accrue events.
        feral = sorted(set(publishers) - {value for _, value in _all_event_types()})
        if feral:
            for event in feral:
                sites = publishers[event]
                first = sites[0]
                print(
                    f"::error file={first[1]},line={first[2]}::"
                    f"Feral event '{event}' — add to EventType or remove publish",
                    file=sys.stderr,
                )
            return 1

        return 1 if drift else 0

    DOCS_ROOT.mkdir(parents=True, exist_ok=True)
    MODULES_CATALOG.write_text(new_modules_text, encoding="utf-8")
    EVENTS_CATALOG.write_text(new_events_text, encoding="utf-8")
    SUBPROCESSORS_CATALOG.write_text(new_subprocessors_text, encoding="utf-8")
    APPS_CATALOG.write_text(new_apps_text, encoding="utf-8")
    ERRORS_CATALOG.write_text(new_errors_text, encoding="utf-8")
    print(f"Wrote {MODULES_CATALOG.relative_to(REPO_ROOT)}")
    print(f"Wrote {EVENTS_CATALOG.relative_to(REPO_ROOT)}")
    print(f"Wrote {SUBPROCESSORS_CATALOG.relative_to(REPO_ROOT)}")
    print(f"Wrote {APPS_CATALOG.relative_to(REPO_ROOT)}")
    print(f"Wrote {ERRORS_CATALOG.relative_to(REPO_ROOT)}")
    print(f"Modules: {len(modules)}  Events: {len(_all_event_types())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
